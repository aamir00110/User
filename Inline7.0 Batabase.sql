    "IP_ADDRESS" VARCHAR2(20), 
    "OLD_COLOR" VARCHAR2(20), 
    "NEW_COLOR" VARCHAR2(20), 
    "CHANGED_BY" VARCHAR2(100), 
    "CHANGED_AT" TIMESTAMP (6) DEFAULT SYSTIMESTAMP, 
     PRIMARY KEY ("LOG_ID")
  USING INDEX  ENABLE
   ) ;